    utils::data("CTCF_in_10a_overlaps_gr", package = "seqsetvis", overwrite = TRUE, envir = environment())
    query_gr = CTCF_in_10a_overlaps_gr
    colnames(GenomicRanges::mcols(query_gr)) = paste0(
        "peak_",
        colnames(GenomicRanges::mcols(query_gr))
