#' translateSSVtoCT2
#'
#' *seqsetvis* creates data.table with certain default variables that
#' *chiptsne2* uses more user-friendly values for. This function checks for
#' *seqsetvis* defaults and converts them to *chiptsne2*.
#'
#' @param prof_dt A data.table generated by *seqsetvis* from ssvFetchGRanges
#'
#' @return The input `prof_dt` with colnames updated to be compatible with
#'   *chiptsne2*.
#' @export
#'
#' @examples
#' prof_dt = exampleProfDT()
#' prof_dt_for_ct2 = translateSSVtoCT2(prof_dt)
#' ct2 = ChIPtsne2.from_tidy(prof_dt_for_ct2, exampleQueryGR())
#'
#' prof_dt_ssv_again = translateCT2toSSV(prof_dt_for_ct2)
#' setequal(colnames(prof_dt), colnames(prof_dt_ssv_again))
translateSSVtoCT2 = function(prof_dt){
    #convert to data.table if needed
    if(!is(prof_dt, "data.table")){
        prof_dt = data.table::as.data.table(prof_dt)
    }
    if("id" %in% colnames(prof_dt)){
        if("region" %in% colnames(prof_dt)){
            stop('Both "id" and "region" found! Can only translate if one or the other is present.')
        }
        data.table::setnames(prof_dt, "id", "region")
    }
    if("x" %in% colnames(prof_dt)){
        if("position" %in% colnames(prof_dt)){
            stop('Both "x" and "position" found! Can only translate if one or the other is present.')
        }
        data.table::setnames(prof_dt, "x", "position")
    }
    if("sample" %in% colnames(prof_dt)){
        if("name" %in% colnames(prof_dt)){
            stop('Both "sample" and "name" found! Can only translate if one or the other is present.')
        }
        data.table::setnames(prof_dt, "sample", "name")
    }
    if("y" %in% colnames(prof_dt)){
        if("value" %in% colnames(prof_dt)){
            stop('Both "y" and "value" found! Can only translate if one or the other is present.')
        }
        data.table::setnames(prof_dt, "y", "value")
    }
    prof_dt[]
}

